function product({ name, category, label, flavor, accent, collection }) {
    const image = savedImages[name] || `/images/products/generated/${slugify(name)}.svg`;

    return {
        name,
        category,
        label,
        flavor,
        collection,
        price: "$40",
        description: `${flavor}${collection ? ` ${collection}.` : "."}`,
        accent: accent || brandAccents[category],
        image,
        imageAlt: `${name} energy drink can`
    };
}

function merchProduct({ name, category, label, price, description, accent, image, kind }) {
    return {
        name,
        category,
        label,
        flavor: description,
        collection: kind,
        price,
        description,
        accent,
        image,
        imageAlt: `${name} product image`
    };
}

function slugify(value) {
    return value
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
}

