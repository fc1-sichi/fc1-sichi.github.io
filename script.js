let activeCategory = "energy";
let activeFilter = "redbull";

function renderVisual(product) {
    const generatedClass = product.image.includes("/generated/") ? " generated-image" : "";
    return `<img class="product-image${generatedClass}" src="${product.image}" alt="${product.imageAlt}">`;
}

function renderProducts(filter = "all") {
    const visibleProducts = activeCategory === "energy"
        ? (filter === "all" ? products : products.filter((product) => product.category === filter))
        : merchProducts.filter((product) => product.category === activeCategory);

    productGrid.innerHTML = visibleProducts.map((product) => `
        <article class="product-card">
            <div class="product-visual" style="--accent: ${product.accent};">
                ${renderVisual(product)}
            </div>
            <div class="product-info">
                <div class="product-meta">
                    <span>${product.label}</span>
                    <span class="price">${product.price}</span>
                </div>
                <div>
                    <h3>${product.name}</h3>
                    <p>${product.description}</p>
                </div>
                <button class="button secondary add-button" type="button" data-product-name="${product.name}">
                    <i class="fa-solid fa-plus"></i>
                    Add to request
                </button>
            </div>
        </article>
    `).join("");
}

function getCart() {
    try {
        return JSON.parse(localStorage.getItem("sichiCart")) || [];
    } catch (error) {
        return [];
    }
}

function saveCart(cart) {
    localStorage.setItem("sichiCart", JSON.stringify(cart));
    updateCartCount();
    renderOrder();
}

function updateCartCount() {
    if (!cartCount) return;
    const count = getCart().reduce((total, item) => total + item.quantity, 0);
    cartCount.textContent = count;
    cartCount.hidden = count === 0;
}

function itemPriceValue(item) {
    const parsedPrice = Number(String(item.price || "").replace(/[^0-9.]/g, ""));
    return Number.isFinite(parsedPrice) && parsedPrice > 0 ? parsedPrice : 40;
}

function cartSubtotal(cart = getCart()) {
    return cart.reduce((total, item) => total + (item.quantity * itemPriceValue(item)), 0);
}

function cartItemCount(cart = getCart()) {
    return cart.reduce((total, item) => total + item.quantity, 0);
}

function addProductToCart(productName) {
    const product = allProducts.find((item) => item.name === productName);
    if (!product) return;

    const cart = getCart();
    const existing = cart.find((item) => item.name === product.name);
    if (existing) {
        existing.quantity += 1;
    } else {
        cart.push({
            name: product.name,
            label: product.label,
            price: product.price,
            image: product.image,
            quantity: 1
        });
    }

    saveCart(cart);
    window.location.href = "/checkout.html";
}

function renderOrder() {
    const cart = getCart();
    const count = cartItemCount(cart);

    orderList.innerHTML = cart.map((item, index) => `
        <li>
            <span>
                <strong>${item.quantity}x ${item.name}</strong>
                <small>${item.label} / ${item.price}</small>
            </span>
            <button class="remove-item" type="button" data-remove-index="${index}" aria-label="Remove ${item.name}">
                <i class="fa-solid fa-xmark"></i>
            </button>
        </li>
    `).join("");

    emptyState.hidden = cart.length > 0;
    cacheTotal.hidden = cart.length === 0;
    cacheCheckout.hidden = cart.length === 0;
    cacheCount.textContent = `${count} item${count === 1 ? "" : "s"} cached`;
    cacheSubtotal.textContent = `$${cartSubtotal(cart)}`;
    updateEmailLink();
}

function updateEmailLink() {
    const formData = new FormData(orderForm);
    const name = formData.get("name") || "";
    const contact = formData.get("contact") || "";
    const notes = formData.get("notes") || "";
    const cart = getCart();
    const list = cart.length
        ? cart.map((item) => `${item.quantity}x ${item.name} (${item.label})`).join(", ")
        : "No products selected yet";
    const body = [
        `Name: ${name}`,
        `Contact: ${contact}`,
        `Products: ${list}`,
        "",
        "Build notes:",
        notes
    ].join("\n");

    emailLink.href = cart.length
        ? "/checkout.html"
        : `mailto:orders@sichi.me?subject=${encodeURIComponent("Custom Sichi order request")}&body=${encodeURIComponent(body)}`;
}

